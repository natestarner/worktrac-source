#!/usr/bin/env node
// Turns a reviewed video mapping (CSV) into a Flyway migration that adds library exercises' how-to
// videos (exercise_videos, V94). Videos arrive by migration like the rest of the library (CLAUDE.md:
// "seed/reference data goes in migrations"); this only writes the file, it touches no database.
//
//   node scripts/video-migration.mjs <mapping.csv> <version> <description>
//   node scripts/video-migration.mjs docs/exercise-videos/batch-1.csv 96 add_first_exercise_videos
//
// The CSV has a header row and four columns:
//   exercise,video_id,start_seconds,source_label
//   Barbell Bench Press,j7ULT6dznNc,12,Muscle & Strength
//
// - exercise must be a LIBRARY exercise's exact name. The migration ends by counting what it matched
//   and THROWS if any row named nothing, so a typo fails the build (every backend test migrates)
//   instead of silently adding no video -- V93's name-matching taught that lesson.
// - video_id is the 11-character YouTube id, never a URL. Anything else is refused here.
// - start_seconds may be blank.
// - Idempotent: an exercise that already has a video is left alone (WHERE NOT EXISTS). Replacing a
//   video is a separate, deliberate UPDATE migration, not a re-run of this.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const [csvPath, versionArg, description] = process.argv.slice(2);
if (!csvPath || !versionArg || !description) {
  console.error('usage: node scripts/video-migration.mjs <mapping.csv> <version> <description>');
  process.exit(1);
}
if (!/^\d+$/.test(versionArg)) fail(`version must be a number, got "${versionArg}"`);
if (!/^[a-z0-9_]+$/.test(description)) fail('description must be snake_case (letters, digits, underscores)');

function fail(message) {
  console.error(`video-migration: ${message}`);
  process.exit(1);
}

// A small CSV reader: quoted fields may hold commas and doubled quotes. Enough for a hand-reviewed
// sheet; no dependency.
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i += 1; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i += 1;
      row.push(field); field = '';
      if (row.some((v) => v.trim() !== '')) rows.push(row);
      row = [];
    } else field += c;
  }
  row.push(field);
  if (row.some((v) => v.trim() !== '')) rows.push(row);
  return rows;
}

const [header, ...body] = parseCsv(readFileSync(csvPath, 'utf8'));
const expected = ['exercise', 'video_id', 'start_seconds', 'source_label'];
if (header?.map((h) => h.trim().toLowerCase()).join(',') !== expected.join(',')) {
  fail(`the header must be exactly: ${expected.join(',')}`);
}
if (body.length === 0) fail('the mapping has no rows');

const seen = new Set();
const entries = body.map((cols, i) => {
  const line = i + 2;
  const [exercise, videoId, start, label] = cols.map((v) => (v ?? '').trim());
  if (!exercise) fail(`line ${line}: no exercise name`);
  if (seen.has(exercise.toLowerCase())) fail(`line ${line}: "${exercise}" appears twice (one video per exercise)`);
  seen.add(exercise.toLowerCase());
  if (!/^[A-Za-z0-9_-]{11}$/.test(videoId)) fail(`line ${line}: "${videoId}" is not an 11-character YouTube id`);
  if (start !== '' && !/^\d{1,5}$/.test(start)) fail(`line ${line}: start_seconds must be blank or whole seconds`);
  if (!label || label.length > 100) fail(`line ${line}: source_label must be 1-100 characters`);
  return { exercise, videoId, start: start === '' ? null : Number(start), label };
});

const nstr = (s) => `N'${s.replace(/'/g, "''")}'`;
const values = entries
  .map((e) => `    (${nstr(e.exercise)}, ${nstr(e.videoId)}, ${e.start ?? 'NULL'}, ${nstr(e.label)})`)
  .join(',\n');

const sql = `-- How-to videos for library exercises (exercise_videos, V94). Generated by
-- scripts/video-migration.mjs from ${path.basename(csvPath)}; edit the mapping and regenerate rather than
-- editing this by hand before it is applied, and never after.
--
-- Matches exercises by exact name among LIBRARY rows only, skips one that already has a video, and
-- throws if any name matched nothing, so a typo fails every backend test instead of adding nothing.
DECLARE @map TABLE (name NVARCHAR(200) NOT NULL, video_id NVARCHAR(11) NOT NULL, start_seconds INT NULL, source_label NVARCHAR(100) NOT NULL);
INSERT INTO @map (name, video_id, start_seconds, source_label) VALUES
${values};

INSERT INTO exercise_videos (exercise_id, video_id, start_seconds, source_label)
SELECT e.id, m.video_id, m.start_seconds, m.source_label
FROM @map m
JOIN exercises e ON e.name = m.name AND e.account_id IS NULL
WHERE NOT EXISTS (SELECT 1 FROM exercise_videos v WHERE v.exercise_id = e.id);

IF EXISTS (
    SELECT 1 FROM @map m
    WHERE NOT EXISTS (SELECT 1 FROM exercises e WHERE e.name = m.name AND e.account_id IS NULL)
)
    THROW 50000, 'V${versionArg}: a video names an exercise that is not in the library', 1;
`;

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'backend', 'src', 'main', 'resources', 'db', 'migration', `V${versionArg}__${description}.sql`);
if (existsSync(out)) fail(`${out} already exists`);
writeFileSync(out, sql);
console.log(`video-migration: wrote ${path.relative(root, out)} (${entries.length} video${entries.length === 1 ? '' : 's'})`);
